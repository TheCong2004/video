"""Reproducible static inventory; candidate bindings are not runtime test results."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CRATES = ROOT / 'src/crates'
rust_files = list(CRATES.rglob('*.rs'))
slint_files = list((CRATES / 'concat/ui').rglob('*.slint'))
bindings = {}
for file in rust_files:
    for line, text in enumerate(file.read_text(encoding='utf-8').splitlines(), 1):
        for name in re.findall(r'\.on_([a-z0-9_]+)\s*\(', text):
            bindings.setdefault(name, []).append(f'{file.relative_to(ROOT).as_posix()}:{line}')
callbacks = []
def coverage(global_name, callback):
    if global_name == 'AiControl':
        mcp = {'submit': 'concat_control_submit', 'refresh': 'concat_control_status (workflow status only)'}.get(callback, 'operator-only; intentionally not granted over MCP')
        return mcp, 'native Control adapter; source + compile checked, full native E2E pending'
    if global_name == 'AiEditing':
        related = {'export-context':'concat_get_context', 'import-plan':'concat_propose_edit', 'submit-web-result':'concat_propose_edit'}.get(callback)
        return (f'related operation: {related}; callback itself remains native' if related else 'native callback; existing MCP exposes scoped context/status/proposal, not this action'), 'existing strict edit bridge; per-callback runtime coverage not established'
    return 'not exposed by current editing/Control MCP', 'requires shared typed adapter'
for file in slint_files:
    text = file.read_text(encoding='utf-8')
    for match in re.finditer(r'(?:export\s+)?global\s+(\w+)\s*\{', text):
        start = match.end()
        depth, end = 1, start
        while end < len(text) and depth:
            depth += (text[end] == '{') - (text[end] == '}')
            end += 1
        for cb in re.finditer(r'callback\s+([\w-]+)\s*\(([^)]*)\)', text[start:end-1]):
            name = cb[1]
            callbacks.append({'global': match[1], 'callback': name, 'signature': cb[2],
                'ui': f'{file.relative_to(ROOT).as_posix()}:{text[:start+cb.start()].count(chr(10))+1}',
                'candidateBindings': bindings.get(name.replace('-', '_'), []),
                'verification': 'static candidate only; not individually runtime-verified',
                'mcp': coverage(match[1],name)[0], 'coverage':coverage(match[1],name)[1]})
api = (CRATES/'concat-api/src/message.rs').read_text(encoding='utf-8').split('/// One template slot')[0]
methods = re.findall(r'#\[serde\(rename = "([\w.]+)"\)\]', api)
mcp_file = ROOT/'tools/ai-edit-mcp/server.mjs'
mcp = re.findall(r"registerTool\(['\"]([^'\"]+)", mcp_file.read_text(encoding='utf-8'))
report = {'scope':'src/crates (excludes third-party patches, binaries, models and dependencies)',
          'crates':sorted(p.parent.name for p in CRATES.glob('*/Cargo.toml')),
          'rustFiles':len(rust_files), 'slintFiles':len(slint_files),
          'apiMethods':methods, 'editingMcpTools':mcp, 'callbacks':callbacks}
out=ROOT/'docs/ai-control'
out.mkdir(exist_ok=True,parents=True)
(out/'inventory.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
lines=['# AI Capability Matrix', '',
       'Generated by `python scripts/audit_ai_capabilities.py`. Static candidates are not proof that a callback works. The existing editing tools and additive Control tools share the native bridge; operator-only actions are not remotely granted.', '',
       f"Inventory: {len(report['crates'])} crates, {len(rust_files)} Rust files, {len(slint_files)} Slint files, {len(callbacks)} global business callbacks, {len(methods)} native API methods.", '',
       '| Global / function | UI location | Current manual operation / business entry | Rust binding candidates | Existing MCP | AI coverage / missing work | Priority | Test status |',
       '|---|---|---|---|---|---|---|---|']
for row in callbacks:
    lines.append('| '+ ' | '.join([f"{row['global']}.{row['callback']}",row['ui'],f"UI callback `{row['callback']}`; exact semantics require adapter review",'<br>'.join(row['candidateBindings']) or 'not found by static scan',row['mcp'],row['coverage'],'P1' if row['global'] in ['AiControl','KediFactory','AiEditing','ProductionScenes'] else 'P2','not individually runtime verified'])+' |')
lines += ['', '## Existing native API methods', '', '\n'.join(f'- `{method}`' for method in methods), '',
          'Native API methods are real entry points but are not automatically tools in the editing MCP. LiveSessionBridge has no production GUI implementation found during the initial audit; do not claim live import/export coverage from trait definitions or fixtures.', '']
lines += ['## Installed Control executors', '',
          'These concrete executors are registered in `src/crates/concat/src/studio_ai_control.rs`. Their registry contracts are validated at dispatch/output boundaries. Native build/GUI acceptance remains separate from core and backend integration tests.', '',
          '| Executor | Existing business service | Permission | Recovery |', '|---|---|---|---|',
          '| `media.inspect` | `concat_media::probe` | attached/owned media read | bounded safe retry |',
          '| `ai.plan` | bounded model DAG compiler | operator-enabled AI network | never replay an unknown request |',
          '| `nexora.pages` | existing Nexora catalogue + linked presets | existing local Nexora settings, read only | safe read retry; profile is not social Page authority |',
          '| `production.generate` | existing Nexora/Grok ProductionClient | actual profile ID, attached anchor, explicit prompts + AI network grant | never auto-replay; existing recovery fence |',
          '| `batch.expand` | bounded compiler: up to 100 jobs into existing workflow store | unique briefs; explicit repeated-story option | atomic graph expansion before child dispatch; no new queue owner |',
          '| `ui.action` | existing native Slint controls: open Factory/Film, paste Film idea | main-window UI only | no automatic replay; stop/takeover releases guard |',
          '| `library.list` | `video_library` actual metadata | library read | bounded safe retry |',
          '| `ai.script` | existing AI client | operator-enabled AI network | no automatic paid replay |',
          '| `ai.edit` | existing AI client + live strict schema | operator-enabled AI network | no automatic paid replay |',
          '| `factory.render` | existing Rust Factory adapter / FFmpeg worker | attached assets + fresh output folder; network grant for online voice | fresh attempt folder, known failures only |',
          '| `artifact.validate` | native media probe + streaming SHA256 | attached/owned media read | bounded safe retry |',
          '| `editor.apply` | existing native strict EditPlan / undo | revision-bound editor write + workflow mode | unknown writes never replayed |', '']
(ROOT/'docs/AI_CAPABILITY_MATRIX.md').write_text('\n'.join(lines),encoding='utf-8')
print(json.dumps({k:v for k,v in report.items() if k!='callbacks'},ensure_ascii=False))
